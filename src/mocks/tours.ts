export function getTour(id: string) {
  return tours.find((t) => t.id === id);
}

export function getToursByDestination(destination: string) {
  return tours.filter((t) => t.destination === destination);
}

export function getToursByLeader(leaderId: string) {
  return tours.filter((t) => t.leaderId === leaderId);
}

export function getRelatedTours(tour: Tour, limit = 4) {
  return tours
    .filter(
      (t) =>
        t.id !== tour.id &&
        (t.destination === tour.destination || t.category === tour.category)
    )
    .slice(0, limit);
}

export function getCompetingTours(tour: Tour) {
  return tours.filter(
    (t) =>
      t.id !== tour.id && t.destination === tour.destination
  );
}
