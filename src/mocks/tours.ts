function makeReviews(seed: string, count: number) {
  const names = [
    "علی رضایی",
    "سارا کریمی",
    "حسین موسوی",
    "زهرا اکبری",
    "محمد جوادی",
    "فاطمه قاسمی",
    "رضا شریفی",
    "نگار صادقی",
  ];
  const comments = [
    "تجربه فوق‌العاده‌ای بود! لیدر تور بسیار حرفه‌ای و مهربان بود و همه‌چیز دقیقاً طبق برنامه پیش رفت.",
    "مناظر بی‌نظیر بود و نظارت لیدر عالی. حتماً دوباره با همین تیم سفر می‌کنم.",
    "بهترین توری که تا حالا رفتم. غذا، اقامت و برنامه‌ریزی عالی بود.",
    "سفری به یاد ماندنی داشتیم. ممنون از تیم حرفه‌ای کوچ‌نشین.",
    "ارزشش رو داشت، گرچه کمی گران بود ولی کیفیت کار بالا بود.",
    "هماهنگی و مدیریت گروه عالی بود. تجربه‌ای امن و لذت‌بخش.",
  ];
  const reviews: Review[] = [];
  for (let i = 0; i < count; i++) {
    const d = new Date();
    d.setDate(d.getDate() - i * 7 - 3);
    reviews.push({
      id: `${seed}_r${i}`,
      author: names[(i + seed.length) % names.length],
      avatar: `https://images.unsplash.com/photo-1507003211169-0a1dd7228f2d?w=100&h=100&fit=crop&crop=faces&q=80`,
      rating: i % 5 === 0 ? 4 : 5,
      date: d.toISOString(),
      comment: comments[(i + seed.length) % comments.length],
      tourId: seed,
    });
  }
  return reviews;
}

