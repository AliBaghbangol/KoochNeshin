export function getBlogPost(id: number) {
  return blogPosts.find((p) => p.id === id);
}

export function getRelatedPosts(currentId: number, limit = 3) {
  return blogPosts
    .filter((p) => p.id !== currentId)
    .slice(0, limit);
}

/**
 * Find the magazine article that introduces a given destination — used by
 * the destinations page «از مجله سفر» section. Some destination names differ
 * from their article tags («قله دماوند» is tagged «دماوند»), hence aliases.
 * Returns undefined when no article covers the destination yet (e.g. کندوان).
 */
const DESTINATION_ARTICLE_ALIASES: Record<string, string> = {
  "قله دماوند": "دماوند",
  "دشت لوت": "کویر لوت",
};

export function getDestinationArticle(destinationName: string): BlogPost | undefined {
  const tag = DESTINATION_ARTICLE_ALIASES[destinationName] ?? destinationName;
  return blogPosts.find((p) => p.tags.includes(tag));
}
